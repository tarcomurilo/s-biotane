    //Render
    protected function render()
    {
        $settings = $this->get_settings_for_display();
        if ($settings['container'] == 'yes') {
            $container = 'container';
        } else {
            $container = 'container-fluid';
        }
        ob_start();
?>
        <div class="eco-icon-box-four-wrapper">
            <div class="<?php echo esc_attr($container); ?>">
                <div class="eco-icon-box-four-item ">
                    <?php if (!empty($settings['icon'])) : ?>
                        <div class="eco-icon-four">
                            <?php \Elementor\Icons_Manager::render_icon($settings['icon'], ['aria-hidden' => 'true']); ?>
                        </div>
                    <?php endif; ?>
                    <?php if ($settings['enable_link'] == 'yes') :
                        if (!empty($settings['link']['url'])) {
                            $this->add_link_attributes('link', $settings['link']);
                        }
                    ?>
                        <a <?php echo $this->get_render_attribute_string('link'); ?>>
                        <?php endif; ?>
                        <?php if (!empty($settings['title'])) : ?>
                            <<?php echo esc_attr($settings['title_tag']); ?> class="icon-box-four-title">
                                <?php echo esc_html($settings['title']); ?>
                            </<?php echo esc_attr($settings['title_tag']); ?>>
                        <?php endif; ?>
                        <?php if ($settings['enable_link'] == 'yes') : ?>
                        </a>
                    <?php endif ?>
                </div>
            </div>
        </div>
<?php
        echo ob_get_clean();
    }
